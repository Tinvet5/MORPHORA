"use strict";
const assert = require("assert");
const provider = require("../histology/histology-source-provider.js");
const xml = `<?xml version="1.0"?><Image TileSize="512" Overlap="1" Format="jpg" xmlns="http://schemas.microsoft.com/deepzoom/2008"><Size Width="83457" Height="97468"/></Image>`;
const info = provider.parseDziDescriptor(xml, "https://tiles.morphora.cl/histology/48515-2/slide.dzi", {micrometresPerPixelX:0.267857,micrometresPerPixelY:0.267857});
assert.equal(info.Width, 83457);
assert.equal(info.Height, 97468);
assert.equal(info.TileSize, 512);
assert.equal(info.TileOverlap, 1);
assert.equal(info.MaxZoomLevel, 17);
assert.equal(provider.tileUrl(info, 17, 2, 3), "https://tiles.morphora.cl/histology/48515-2/slide_files/17/2_3.jpg");
assert.deepEqual(provider.resolveCandidates({mode:"auto",hostedDescriptorUrl:"https://x/slide.dzi",localAvailable:true}), ["hosted-dzi","pma-start"]);
assert.deepEqual(provider.resolveCandidates({mode:"auto",hostedDescriptorUrl:"",localAvailable:true}), ["pma-start"]);
assert.deepEqual(provider.resolveCandidates({mode:"hosted",hostedDescriptorUrl:"",localAvailable:true}), []);
assert.deepEqual(provider.resolveCandidates({mode:"local",hostedDescriptorUrl:"https://x/slide.dzi",localAvailable:true}), ["pma-start"]);
console.log("Histology hosted-source provider checks passed.");
